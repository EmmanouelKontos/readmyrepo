import { AuditFinding, DependencyEdge, RepoNode, RepoScores } from '../types/atlas';

export function compileAgentsMdBlueprint(
  repoName: string,
  description: string,
  nodes: RepoNode[],
  edges: DependencyEdge[],
  findings: AuditFinding[],
  scores: RepoScores
): { agentsMdBlueprint: string; masterFixPrompt: string } {
  const byLayer = {
    entry: nodes.filter((n) => n.layer === 'entry'),
    ui: nodes.filter((n) => n.layer === 'ui'),
    feature: nodes.filter((n) => n.layer === 'feature'),
    service: nodes.filter((n) => n.layer === 'service'),
    data: nodes.filter((n) => n.layer === 'data'),
    config: nodes.filter((n) => n.layer === 'config'),
  };

  const godFiles = nodes.filter((n) => n.isGodFile);
  const cyclicEdges = edges.filter((e) => e.isCircular);

  const layerSummary = Object.entries(byLayer)
    .filter(([, list]) => list.length > 0)
    .map(
      ([layer, list]) =>
        `- **${layer.toUpperCase()} Layer (${list.length} files)**: ${list
          .map((n) => `\`${n.path}\` (${n.linesOfCode} LOC)`)
          .join(', ')}`
    )
    .join('\n');

  const hotspotSummary =
    godFiles.length > 0
      ? godFiles
          .map(
            (g) =>
              `- \`${g.path}\` (${g.linesOfCode} LOC) — exceeds 220-line modularity threshold; split UI primitives, hooks, and service calls.`
          )
          .join('\n')
      : '- All modules currently respect the <220 LOC modularity cap.';

  const cycleSummary =
    cyclicEdges.length > 0
      ? cyclicEdges.map((c) => `- Circular import: \`${c.from}\` <-> \`${c.to}\``).join('\n')
      : '- Zero circular dependencies detected.';

  const agentsMdBlueprint = `# AGENTS.md — ${repoName} Architecture & AI Guardrails
> Auto-generated by **RepoAtlas** | Health Score: **${scores.overall}/100** (Arch ${scores.architecture} · Sec ${scores.security} · Perf ${scores.performance})
> Total Context Footprint: **~${scores.totalTokens.toLocaleString()} tokens** across **${scores.totalFiles} files** (${scores.totalLines.toLocaleString()} LOC)

## 1. System Overview
${description}

## 2. Verified Module Topology & Layer Boundaries
${layerSummary}

## 3. Strict Dependency Direction Rules
1. **Entry -> Feature -> UI / Service -> Data**:
   - \`ui/\` components MUST stay stateless and never import from \`feature/\` or \`service/\`.
   - Raw SQL/Supabase/fetch calls MUST live inside \`service/\` or \`lib/\`, never directly inside JSX view trees.
2. **Modularity Cap (< 220 LOC)**:
   - Keep every component and module under 220 lines.

## 4. Current Architectural Hotspots to Respect / Refactor
### Oversized Modules (Spaghetti Risk)
${hotspotSummary}

### Circular Dependencies
${cycleSummary}
`;

  const criticalAndHigh = findings.filter(
    (f) => f.severity === 'critical' || f.severity === 'high'
  );
  const otherFindings = findings.filter(
    (f) => f.severity !== 'critical' && f.severity !== 'high'
  );
  const ordered = [...criticalAndHigh, ...otherFindings];

  const masterFixPrompt =
    ordered.length === 0
      ? `All security, performance, and architecture checks passed for ${repoName}!`
      : `You are refactoring **${repoName}**. Please resolve the following ${ordered.length} prioritized findings detected by RepoAtlas while preserving all existing functionality and keeping every file under 220 lines:\n\n` +
        ordered
          .map(
            (f, idx) =>
              `### ${idx + 1}. [${f.severity.toUpperCase()}] ${f.ruleId}: ${f.title}\n` +
              `- **File**: \`${f.filePath}:${f.lineNumber}\`\n` +
              `- **Why it matters**: ${f.explanation}\n` +
              `- **Required Action**: ${f.remediation}`
          )
          .join('\n\n');

  return { agentsMdBlueprint, masterFixPrompt };
}
